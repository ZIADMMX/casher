/**
 * foxcloud POS - create the vendor's license signing key (run once).
 *
 *   node scripts/license-init.js
 *
 * Writes the Ed25519 private key outside the repository and embeds the matching
 * public key in electron/security/license-public-key.js. Refuses to overwrite an
 * existing private key: replacing it invalidates every license already issued.
 */
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { privateKeyPath } = require('./lib/license-private-key');

const keyFile = privateKeyPath();
const publicKeyModule = path.join(__dirname, '..', 'electron', 'security', 'license-public-key.js');

function writePublicKeyModule(publicKey) {
  const spki = publicKey.export({ format: 'der', type: 'spki' }).toString('base64');
  const source = `// Generated by scripts/license-init.js. Public half of the vendor's Ed25519
// license signing key. Safe to ship: it can verify license keys, not create them.
const LICENSE_PUBLIC_KEY = '${spki}';

module.exports = { LICENSE_PUBLIC_KEY };
`;
  fs.writeFileSync(publicKeyModule, source);
  return spki;
}

if (fs.existsSync(keyFile)) {
  const existing = crypto.createPrivateKey(fs.readFileSync(keyFile));
  const spki = writePublicKeyModule(crypto.createPublicKey(existing));
  console.log(`مفتاح التوقيع موجود بالفعل: ${keyFile}`);
  console.log(`تم تحديث المفتاح العام في البرنامج: ${spki}`);
  process.exit(0);
}

const { privateKey, publicKey } = crypto.generateKeyPairSync('ed25519');
fs.mkdirSync(path.dirname(keyFile), { recursive: true });
fs.writeFileSync(keyFile, privateKey.export({ format: 'pem', type: 'pkcs8' }), { mode: 0o600, flag: 'wx' });
const spki = writePublicKeyModule(publicKey);

console.log(`
======================================================
تم إنشاء مفتاح توقيع التراخيص
======================================================
المفتاح الخاص : ${keyFile}
المفتاح العام  : ${spki}

مهم جدًا:
- اعمل نسخة احتياطية من المفتاح الخاص في مكان آمن (فلاشة مشفرة أو مدير كلمات مرور).
  لو ضاع، مش هتقدر تطلع تراخيص للعملاء الحاليين.
- ماتحطوش في المستودع ولا تبعته لحد.
- اعمل commit لملف electron/security/license-public-key.js.
======================================================
`);
