/**
 * foxcloud POS - create the time server's signing key (run once).
 *
 *   node scripts/time-server-init.js                 create the key, embed its public half in the app
 *   node scripts/time-server-init.js --print-secret  print the private key for the Worker:
 *     node scripts/time-server-init.js --print-secret | npx wrangler secret put TIME_SIGNING_KEY
 *
 * Separate from the license key on purpose: if the server is ever compromised,
 * the attacker can fake time answers but still cannot mint license keys.
 */
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const keyFile = process.env.FOX_TIME_PRIVATE_KEY_FILE
  || path.join(os.homedir(), '.foxcloud', 'time-server-key.pem');
const publicKeyModule = path.join(__dirname, '..', 'electron', 'security', 'time-server-public-key.js');

if (process.argv.includes('--print-secret')) {
  if (!fs.existsSync(keyFile)) {
    console.error(`مفتاح سيرفر الوقت غير موجود في ${keyFile}. شغّل: node scripts/time-server-init.js`);
    process.exit(1);
  }
  const key = crypto.createPrivateKey(fs.readFileSync(keyFile));
  process.stdout.write(key.export({ format: 'der', type: 'pkcs8' }).toString('base64'));
  process.exit(0);
}

let privateKey;
if (fs.existsSync(keyFile)) {
  privateKey = crypto.createPrivateKey(fs.readFileSync(keyFile));
  console.log(`مفتاح سيرفر الوقت موجود بالفعل: ${keyFile}`);
} else {
  privateKey = crypto.generateKeyPairSync('ed25519').privateKey;
  fs.mkdirSync(path.dirname(keyFile), { recursive: true });
  fs.writeFileSync(keyFile, privateKey.export({ format: 'pem', type: 'pkcs8' }), { mode: 0o600, flag: 'wx' });
  console.log(`تم إنشاء مفتاح سيرفر الوقت: ${keyFile}`);
}

const spki = crypto.createPublicKey(privateKey).export({ format: 'der', type: 'spki' }).toString('base64');
fs.writeFileSync(publicKeyModule, `// Generated by scripts/time-server-init.js. Public half of the time server's
// Ed25519 key: the app uses it to check that time and trial answers really come
// from the foxcloud license server.
const TIME_SERVER_PUBLIC_KEY = '${spki}';

module.exports = { TIME_SERVER_PUBLIC_KEY };
`);
console.log(`تم تحديث المفتاح العام في البرنامج: ${spki}`);
